import { prisma } from "./prisma";
import { getEffectiveTotal, recalculatePaymentStatus } from "./payment-status";
import { isCreditUsedNote } from "./customer-credit";

/**
 * Customer payments are just money movements: there is no persisted
 * per-order allocation. The original POST distributes a payment FIFO across
 * unpaid orders, so editing or deleting a payment has to reproduce the same
 * logic in reverse instead of "un-applying" a stored allocation:
 *
 * - reducing/deleting a payment claws the money back from the newest orders
 *   first (the inverse of oldest-first FIFO),
 * - increasing a payment pushes the difference through the orders oldest
 *   first, and anything beyond the outstanding debt stays as money under the
 *   customer's account (same behaviour as overpaying in the payment form).
 *
 * Payments tied to a specific order (upfront cash and order payments written
 * by the sales screens) are applied to that order only. Under-account credit
 * rows (`CREDIT_USED_PREFIX`) are generated by the invoice itself, so they are
 * locked: editing them here would double-count the credit.
 */

type PrismaTx = Parameters<Parameters<typeof prisma.$transaction>[0]>[0];

export class PaymentSyncError extends Error {
  code: string;
  constructor(code: string) {
    super(code);
    this.name = "PaymentSyncError";
    this.code = code;
  }
}

/** Order ids embedded in the notes written by the sales screens. */
export function linkedOrderIdFromNotes(notes: string | null | undefined): string | null {
  if (!notes) return null;
  const trimmed = notes.trim();
  if (!trimmed) return null;

  if (isCreditUsedNote(trimmed)) {
    return trimmed.split("—").pop()?.trim() || null;
  }
  if (trimmed.includes("فاتورة بيع") || trimmed.includes("فاتوره بيع")) {
    const last = trimmed.split(/\s+/).pop() || "";
    return /^[A-Za-z0-9_-]{6,}$/.test(last) ? last : null;
  }
  return null;
}

/** Rows generated when an invoice consumes under-account credit. */
export function isLockedCustomerPayment(notes: string | null | undefined): boolean {
  return isCreditUsedNote(notes);
}

async function findLinkedOrder(tx: PrismaTx, customerId: string, orderId: string) {
  const order = await tx.salesOrder.findUnique({
    where: { id: orderId },
    select: { id: true, customerId: true, total: true, paidAmount: true, paymentMethod: true },
  });
  if (!order || order.customerId !== customerId) return null;
  return order;
}

/**
 * Apply a signed delta (positive = more money paid, negative = money removed)
 * to the customer's orders and recompute the payment status of every touched
 * order.
 */
export async function applyCustomerPaymentDelta(
  tx: PrismaTx,
  customerId: string,
  delta: number,
  preferredOrderId?: string | null,
): Promise<void> {
  if (Math.abs(delta) < 0.001) return;

  if (delta > 0) {
    let remaining = delta;
    const linked = preferredOrderId
      ? await findLinkedOrder(tx, customerId, preferredOrderId)
      : null;

    if (linked) {
      const effectiveTotal = await getEffectiveTotal(tx, linked.id, linked.total);
      const outstanding = Math.max(0, effectiveTotal - linked.paidAmount);
      if (remaining > outstanding + 0.01) {
        throw new PaymentSyncError("EXCEEDS_ORDER_LIMIT");
      }
      const applied = Math.min(remaining, outstanding);
      await tx.salesOrder.update({
        where: { id: linked.id },
        data: { paidAmount: { increment: applied } },
      });
      await recalculatePaymentStatus(tx, linked.id);
      return;
    }

    const unpaidOrders = await tx.salesOrder.findMany({
      where: {
        customerId,
        paymentMethod: { not: "CASH" },
        paymentStatus: { notIn: ["PAID"] },
      },
      select: { id: true, total: true, paidAmount: true },
      orderBy: [{ orderDate: "asc" }, { createdAt: "asc" }],
    });

    for (const order of unpaidOrders) {
      if (remaining <= 0) break;
      const effectiveTotal = await getEffectiveTotal(tx, order.id, order.total);
      const outstanding = effectiveTotal - order.paidAmount;
      if (outstanding <= 0) continue;
      const applied = Math.min(remaining, outstanding);
      remaining -= applied;
      await tx.salesOrder.update({
        where: { id: order.id },
        data: { paidAmount: { increment: applied } },
      });
      await recalculatePaymentStatus(tx, order.id);
    }
    return;
  }

  let remaining = -delta;
  const linked = preferredOrderId
    ? await findLinkedOrder(tx, customerId, preferredOrderId)
    : null;

  if (linked) {
    const applied = Math.min(remaining, Math.max(0, linked.paidAmount));
    if (applied > 0) {
      await tx.salesOrder.update({
        where: { id: linked.id },
        data: { paidAmount: { decrement: applied } },
      });
      await recalculatePaymentStatus(tx, linked.id);
    }
    return;
  }

  const paidOrders = await tx.salesOrder.findMany({
    where: {
      customerId,
      paymentMethod: { not: "CASH" },
      paidAmount: { gt: 0 },
    },
    select: { id: true, total: true, paidAmount: true },
    orderBy: [{ orderDate: "desc" }, { createdAt: "desc" }],
  });

  for (const order of paidOrders) {
    if (remaining <= 0) break;
    const applied = Math.min(remaining, order.paidAmount);
    if (applied <= 0) continue;
    remaining -= applied;
    await tx.salesOrder.update({
      where: { id: order.id },
      data: { paidAmount: { decrement: applied } },
    });
    await recalculatePaymentStatus(tx, order.id);
  }
}
